"""Render analysis tables from the immutable calculated artifacts."""
import csv

from common import HERE, load


def main():
    evaluation = load(HERE / 'evaluation.json')
    performance = load(HERE / 'performance.json')
    comparisons = load(HERE / 'comparison.json')['metrics']
    config = load(HERE / 'best_config.json')
    spec = load(HERE / 'hypotheses.json')['categories']
    best = load(HERE / 'development-best.json')
    primary = evaluation['b500-fp32']
    lines = ['# Horizon: 12 пользовательских категорий MICE', '',
        '## Статус и границы', '',
        'Реальные CUDA-прогоны RTX 4060; существующее изолированное HF-окружение. '
        'Веса Horizon не изменялись, обучения не было. Рабочий конвейер, Docker и БД не запускались и не менялись. '
        'B-6000 не использовался. Протокол: `PROTOCOL.md`. Восемь гипотез на категорию (96 всего), '
        'RU/EN, краткие/подробные/действия/исключения. Перебраны 131 328 решений на B-350+B-400, '
        'включая пороги 0.10–0.95 с шагом 0.05, одиночные и составные гипотезы и четыре агрегации.', '',
        'B-500 — отложенный относительно настройки Horizon, **но уже использованный ранее в MICE синтетический корпус**. '
        'Конфигурация и гипотезы зафиксированы отдельным коммитом до первого инференса B-500. '
        'Порог в таблице оптимален на объединённых B-350/B-400, не подбирался на B-500. '
        'FP16 проверен с теми же решениями; его собственный development-оптимум не использован.', '',
        'Тексты — сохранённое фактическое извлечение писем/вложений, включая доступный OCR. '
        'SHA256 каждого EML проверен. В модель передаются только тексты, без разметки, ground-truth OCR, '
        'сценариев и результатов детекторов. Полные журналы извлечения содержат такие поля, но они отделены '
        'от файлов входов инференса. Использован имеющийся OCR-кэш 6 изображений B-350 и 50 B-400; '
        'новый OCR не выполнялся и эталонные тексты изображений не подставлялись. В выбранных observations '
        'все сообщения имеют статус ANALYZED; исторические ограничения/ошибки OCR остаются в фактических текстах.', '',
        'Выход модели: два логита `not_entailment=0`, `entailment=1`; используется softmax по этим двум логитам. '
        'Категории независимы, без softmax между категориями. Фрагменты 900 символов с перекрытием 100, '
        'до 512 токенов пары, обрезается только premise. TF32 выключен; FP32 основной режим.', '',
        '## Итог B-500', '',
        '| Метод | TP | FP | FN | TN | Micro F1 | Macro F1 | Безопасных писем с FP |',
        '|---|---:|---:|---:|---:|---:|---:|---:|']
    for name, m in [('Horizon FP32', primary), ('Horizon FP16', evaluation['b500-fp16']), *[(k.upper(), v) for k, v in comparisons.items()]]:
        a = m['micro']
        lines.append(f"| {name} | {a['TP']} | {a['FP']} | {a['FN']} | {a['TN']} | {a['F1']:.4f} | {m['macro_F1']:.4f} | {m['safe_messages_with_FP']}/{m['safe_messages']} ({m['safe_message_FP_rate']:.2%}) |")
    lines += ['', 'Сопоставимость: точное совпадение SHA256 B-500 manifest и сохранённых observations с метаданными '
        'ML-эксперимента, всех 500 ID, 12 категорий и каждой метки проверено. Сравнение использует прежние '
        'сохранённые предсказания RU3/RU4/TF-IDF/SetFit/RuBERT, не новый прогон этих методов. '
        'Независимая воспроизводимость старых движков здесь не проверялась. Нельзя приписывать разницу только архитектуре: '
        'отличаются обучение, настройка, окно контекста и вычислительные условия. Подробности: `comparison.json`.', '',
        '### Категории: фиксированная конфигурация', '',
        '| Категория | TP/FP/FN/TN | Precision | Recall | F1 | PR-AUC (AP) | FPR | Safe FP | Порог | Гипотезы; комбинация; фрагменты |',
        '|---|---|---:|---:|---:|---:|---:|---:|---:|---|']
    for c, m in primary['per_category'].items():
        cfg = config['categories'][c]
        lines.append(f"| {c.removeprefix('pack-ru2-')} | {m['TP']}/{m['FP']}/{m['FN']}/{m['TN']} | {m['precision']:.3f} | {m['recall']:.3f} | {m['F1']:.3f} | {m['PR_AUC_AP']:.3f} | {m['FPR']:.3%} | {m['safe_FP']}/{m['safe_messages']} | {cfg['threshold']:.2f} | {'+'.join(cfg['hypotheses'])}; {cfg['combine']}; {cfg['aggregation']} |")
    lines += ['', 'PR-AUC — tie-aware average precision, не трапецеидальная площадь. '
        'FPR — FP/(FP+TN) по отрицательным примерам категории. Safe — отсутствие всех 12 пользовательских меток; '
        'это не обязательно отсутствие встроенных структурных ПДн. Суммарная доля safe-писем с любым FP показана выше. '
        'Полные метрики всех корпусов и обоих режимов: `summary.csv`, `evaluation.json`.', '',
        '### Выбранные формулировки и назначение MICE', '']
    for c, cfg in config['categories'].items():
        lines += [f"#### {c}", '', spec[c]['mice_description'], '']
        lines += [f"- `{h['id']}` ({h['polarity']}, {h['language']}): {h['text']}" for h in spec[c]['hypotheses'] if h['id'] in cfg['hypotheses']]
        base = {e: comparisons[e]['per_category'][c]['F1'] for e in comparisons}
        strongest = max(base, key=base.get)
        m = primary['per_category'][c]
        if m['precision'] >= .9 and m['recall'] >= .8:
            verdict = 'Перспективен как дополнительный сигнал на этом корпусе, но не основание автоматической блокировки.'
        elif m['F1'] >= .6:
            verdict = 'Условно полезен как дополнительный сигнал с проверкой человеком; качество и порог требуют независимой проверки.'
        else:
            verdict = 'Недостаточен как самостоятельный детектор; нужен контекстный обучаемый классификатор и независимая разметка.'
        lines += ['', verdict + f" Лучший прежний метод: {strongest.upper()} F1={base[strongest]:.3f}; Horizon F1={m['F1']:.3f}. " +
                  ('Horizon уступает ему.' if m['F1'] < base[strongest] else 'В этом сохранённом сравнении Horizon не уступает по F1.'), '']
    lines += ['## Development: короткие/длинные, комбинации и исключения', '',
        '| Категория | Лучший single F1 | Лучший positive ensemble F1 | Лучший exclusion F1 | Выбранное F1 |',
        '|---|---:|---:|---:|---:|']
    for c, result in best['fp32'].items():
        lines.append(f"| {c.removeprefix('pack-ru2-')} | {result['single']['development']['F1']:.3f} | {result['ensemble']['development']['F1']:.3f} | {result['exclusion']['development']['F1']:.3f} | {result['best']['development']['F1']:.3f} |")
    lines += ['', 'Это оптимистичные development-оценки после широкого перебора, не дополнительный тест. '
        'Все варианты, пороги, FP и FN сохранены в `development-grid.jsonl.gz`; '
        'длина формулировки не используется как критерий выбора. Исключения могут уменьшать recall '
        'в смешанных письмах; применяются внутри фрагмента, а не глобальным вето.', '',
        '## Длина и обфускация (B-500 FP32)', '',
        '| Подвыборка | Micro F1 | Precision | Recall | TP/FP/FN/TN |', '|---|---:|---:|---:|---|']
    for name, value in primary['slices'].items():
        m = value['micro']
        lines.append(f"| {name} | {m['F1']:.3f} | {m['precision']:.3f} | {m['recall']:.3f} | {m['TP']}/{m['FP']}/{m['FN']}/{m['TN']} |")
    lines += ['', 'Группы — исходные группы корпуса, не искусственно созданные здесь и не входные признаки. '
        'Срезы не являются парным экспериментом: различаются также содержание и состав меток. '
        '**Ограничение:** максимум длины извлечённых текстов B-350/B-400/B-500 — 651/318/177 символов. '
        'Все сообщения укладываются в один 900-символьный фрагмент. Поэтому четыре способа агрегации '
        'здесь вырождаются в одно значение; выбранный max — результат tie-break, а не доказательство преимущества. '
        'Влияние действительно длинных писем и нескольких фрагментов **не измерено**. Код обработки таких '
        'писем покрыт offline-тестами, но реального качества/latency на них эти корпуса не дают. '
        'Новый корпус или искусственное удлинение не создавались. Noisy-OR не является калиброванной '
        'вероятностью из-за зависимости перекрывающихся окон.', '', '## Производительность', '',
        '| Набор / режим | Гипотез | Mean с | p50 с | p95 с | Писем/с | Peak RSS МиБ | Allocated VRAM МиБ |',
        '|---|---:|---:|---:|---:|---:|---:|---:|']
    for name, m in performance.items():
        if 'mean_seconds' in m:
            lines.append(f"| {name} | {m['hypotheses']} | {m['mean_seconds']:.4f} | {m['p50_seconds']:.4f} | {m['p95_seconds']:.4f} | {m['messages_per_second']:.2f} | {m['peak_rss_bytes']/2**20:.1f} | {m['peak_vram_allocated_bytes']/2**20:.1f} |")
    lines += ['', 'Время — warmed inference 12 категорий, включая токенизацию и передачи CUDA, '
        'без загрузки модели, извлечения и записи результатов. RSS — process high-water mark (включает загрузку); '
        'VRAM — PyTorch allocated/reserved, не общий расход desktop GPU. Development считает 96 гипотез, '
        'B-500 — только объединение выбранных. Поэтому ускорение между этими наборами не является эффектом FP16.', '',
        '### Число гипотез: фиксированные первые 12 писем B-350, три повтора', '',
        '| Режим | Гипотез | Mean с | p50 с | p95 с | Писем/с |', '|---|---:|---:|---:|---:|---:|']
    for dtype in ('fp32', 'fp16'):
        for n, m in performance.get(f'speed-{dtype}', {}).get('groups', {}).items():
            lines.append(f"| {dtype} | {n} | {m['mean_seconds']:.4f} | {m['p50_seconds']:.4f} | {m['p95_seconds']:.4f} | {m['messages_per_second']:.2f} |")
    delta = performance['fp16_quality_delta']
    lines += ['', f"FP16 против FP32 на B-500: изменённых бинарных решений {delta['changed_decisions']}/6000, "
        f"максимальная абсолютная разница score {delta['max_score_delta']:.6f}, ΔMicro F1={delta['micro_F1']:.6f}. "
        'Сравнение не доказывает численную эквивалентность для других GPU/версий библиотек.', '',
        '## Примеры ошибок B-500 FP32', '']
    errors = list(csv.DictReader((HERE / 'errors.csv').open()))
    for c in categories_from(config):
        subset = [r for r in errors if r['corpus'] == 'b500' and r['dtype'] == 'fp32' and r['category'] == c]
        lines += [f'### {c}', '']
        for kind in ('FP', 'FN'):
            chosen = next((r for r in subset if r['error'] == kind), None)
            if chosen:
                excerpt = chosen['text'].replace('\n', ' ').replace('\r', ' ')[:650]
                lines += [f"- {kind} `{chosen['id']}`, score={float(chosen['score']):.4f}, порог={chosen['threshold']}: «{excerpt}»"]
            else:
                lines += [f'- {kind}: не наблюдались.']
        lines += ['']
    lines += ['Все ошибочные тексты и scores доступны в `errors.csv`. Это синтетические письма; '
        'ошибки извлечения нельзя автоматически считать ошибками только модели. Разметка не исправлялась по результатам.', '',
        '## Универсальный Zero-shot метод в MICE: оценка, не реализация', '',
        'Технически возможен независимый дополнительный метод: администратор задаёт версионированные '
        'положительные/исключающие NLI-гипотезы, язык, правило комбинации, агрегацию и порог каждой категории. '
        'Один общий неизменяемый encoder обслуживает категории пакетами, без обучения новых весов. '
        'Нужны очередь GPU, лимиты количества гипотез/длины текста, кэш по hash текста+версии модели+гипотез, '
        'наблюдаемость времени/памяти, фиксирование evidence-фрагмента и score, журнал изменений конфигурации. '
        'Нельзя выдавать NLI-score за вероятность нарушения или юридическое доказательство.', '',
        'Администраторская гипотеза требует калибровочных положительных и трудных отрицательных примеров; '
        'изменение формулировки требует повторной валидации. Данные письма остаются premise, а не инструкциями. '
        'Исключение должно работать локально и не скрывать реальную угрозу в смешанном тексте. '
        'Для раскрытия/эксфильтрации нужны направление доставки и права получателей — текстовый benchmark '
        'не доказывает их наличие. Структурные ПДн и секреты лучше оставить специализированным детекторам. '
        'Неустойчивые категории требуют обучаемого контекстного классификатора с independently reviewed gold, '
        'а не бесконечной подстройки на B-500.', '',
        'На основании только синтетических данных нельзя рекомендовать автозапрет доставки. '
        'Разумный следующий шаг — отдельно согласованный shadow-mode и независимый корпус с ручной разметкой, '
        'включая новости/цитаты, отрицания, смешанные письма, реально длинные вложения и обфускацию. '
        'В данном PR никакой интеграции Horizon в MICE нет.', '']
    with (HERE / 'REPORT.md').open('x', encoding='utf-8') as stream:
        stream.write('\n'.join(lines))


def categories_from(config):
    return config['categories']


if __name__ == '__main__':
    main()