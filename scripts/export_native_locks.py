"""Derive isolated exact-version dependency closures from the reviewed source lock.

No resolution/network access. Preserve dependency markers, including Windows-only
packages that otherwise break Linux builds. Regenerate after updating uv.lock.
"""

import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEEDS = {
    "parser": "beautifulsoup4 extract-msg httpx oletools openpyxl pillow presidio-analyzer pydantic-settings pymupdf python-docx python-pptx razdel pymorphy3 yara-python",
    "ocr": "rapidocr paddleocr paddlepaddle",
    "training": "scikit-learn",
    "semantic": "fastembed",
}


def export():
    lock = tomllib.loads((ROOT / "uv.lock").read_text())
    packages = {}
    for package in lock["package"]:
        packages.setdefault(package["name"], []).append(package)
    for group, seeds in SEEDS.items():
        found, todo = {}, [(name, None) for name in seeds.split()]
        while todo:
            name, marker = todo.pop()
            if marker and re.search(r"sys_platform == 'win32'|platform_system == 'Windows'", marker):
                continue
            if name in found:
                continue
            candidates = packages[name]
            if len(candidates) != 1:
                raise ValueError("Ambiguous locked package: " + name)
            package = candidates[0]
            found[name] = package["version"]
            todo.extend((item["name"], item.get("marker")) for item in package.get("dependencies", []))
        forbidden = set(found) & {"fastapi", "sqlalchemy", "alembic", "redis"}
        if forbidden:
            raise ValueError("Forbidden dependency closure: " + str(forbidden))
        output = "# Generated by scripts/export_native_locks.py from uv.lock; Linux image.\n"
        output += "\n".join(f"{name}=={version}" for name, version in sorted(found.items())) + "\n"
        (ROOT / f"requirements.{group}.lock").write_text(output)


if __name__ == "__main__":
    export()